"""Trail parser (T2) — read a trail markdown file back into structured data.

The inverse of polish.py:format_trail_markdown (the writer). Existing trails live only as
markdown on disk (the `trails` DB table is empty), so scoring them requires reconstructing
the trail_idea + excerpts that trail_constraints.py / the judge expect.

Returns a TrailDoc with:
  - title, description, rationale          (the trail_idea fields)
  - books: list of {title, author, excerpt_count}   (from the "Books in Trail" block)
  - excerpts: list of {sequence_order, book_title, author, connection_note, text}

Note on author: the rendered markdown carries author="None"; the real author is embedded in
the book_title string as "<Title>   <Author>" (3-space delimiter). Author resolution lives in
trail_facts.resolve_author, not here — the parser preserves the raw strings faithfully.
"""

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional

_TITLE_RE = re.compile(r"^#\s+(.+?)\s*$", re.MULTILINE)
_DESC_RE = re.compile(r"^\*\*Description\*\*:\s*(.+?)\s*$", re.MULTILINE)
_RATIONALE_RE = re.compile(r"^\*\*Rationale\*\*:\s*(.+?)\s*$", re.MULTILINE)
_BOOK_LINE_RE = re.compile(r'^-\s+"(.+?)"\s+by\s+(.+?)\s+\((\d+)\s+excerpts?\)\s*$', re.MULTILINE)
_EXCERPT_HDR_RE = re.compile(r"^###\s+Excerpt\s+(\d+):\s*(.+?)\s*$", re.MULTILINE)
_AUTHOR_RE = re.compile(r"^\*\*Author\*\*:\s*(.+?)\s*$", re.MULTILINE)
_CONNECTION_RE = re.compile(r"^\*\*Connection\*\*:\s*(.+?)\s*$", re.MULTILINE)
_SETTING_RE = re.compile(r"^\*\*Setting\*\*:\s*(.+?)\s*$", re.MULTILINE)
_FOOTER_RE = re.compile(r"\n---\s*\n\s*\*Generated by Syntopic", re.DOTALL)
# Optional "## The synthesis (draft)" section (added after the last excerpt, before the
# footer, when synthesis generation is enabled — see polish.py:format_trail_markdown).
# Trimmed out here too so it doesn't leak into the last excerpt's parsed text.
_SYNTHESIS_SECTION_RE = re.compile(r"\n---\s*\n\s*## The synthesis \(draft\)", re.DOTALL)


@dataclass
class TrailDoc:
    path: str
    title: str
    description: str
    rationale: str
    books: List[Dict] = field(default_factory=list)
    excerpts: List[Dict] = field(default_factory=list)

    @property
    def trail_idea(self) -> Dict:
        """The shape trail_constraints / the judge expect for trail-level metadata."""
        return {"title": self.title, "description": self.description, "rationale": self.rationale}


def _first(rx: re.Pattern, text: str, default: str = "") -> str:
    m = rx.search(text)
    return m.group(1).strip() if m else default


def _parse_books(text: str) -> List[Dict]:
    """Parse the '### Books in Trail:' block. Returns [{title, author, excerpt_count}]."""
    start = text.find("### Books in Trail:")
    if start == -1:
        return []
    # Stop at the next section header (Key Topics / Trail Excerpts / hr).
    rest = text[start:]
    end = len(rest)
    for marker in ("### Key Topics:", "## Trail Excerpts", "\n---\n"):
        i = rest.find(marker, len("### Books in Trail:"))
        if i != -1:
            end = min(end, i)
    block = rest[:end]
    books = []
    for m in _BOOK_LINE_RE.finditer(block):
        books.append({
            "title": m.group(1).strip(),
            "author": m.group(2).strip(),  # usually "None" in rendered trails
            "excerpt_count": int(m.group(3)),
        })
    return books


def _strip_excerpt_text(raw: str) -> str:
    """Take the raw region after the Connection line; strip the leading blockquote marker."""
    body = raw.strip()
    # Drop a leading '> ' from the first line; the writer only quotes the first line.
    if body.startswith(">"):
        body = body[1:].lstrip()
    return body.strip()


def _parse_excerpts(text: str) -> List[Dict]:
    """Parse the '## Trail Excerpts' section into ordered excerpt dicts."""
    sec_start = text.find("## Trail Excerpts")
    if sec_start == -1:
        return []
    section = text[sec_start:]
    # Trim the optional synthesis section and/or the generated footer, if present —
    # whichever appears first (synthesis, when present, precedes the footer).
    for marker_re in (_SYNTHESIS_SECTION_RE, _FOOTER_RE):
        m = marker_re.search(section)
        if m:
            section = section[: m.start()]

    headers = list(_EXCERPT_HDR_RE.finditer(section))
    excerpts: List[Dict] = []
    for idx, hdr in enumerate(headers):
        seq = int(hdr.group(1))
        book_title = hdr.group(2).strip()
        block_start = hdr.end()
        block_end = headers[idx + 1].start() if idx + 1 < len(headers) else len(section)
        block = section[block_start:block_end]

        author = _first(_AUTHOR_RE, block, "None")
        setting = _first(_SETTING_RE, block, "")
        conn_m = _CONNECTION_RE.search(block)
        connection = conn_m.group(1).strip() if conn_m else ""
        # Excerpt text is everything after the connection line.
        text_region = block[conn_m.end():] if conn_m else block
        excerpts.append({
            "sequence_order": seq,
            "book_title": book_title,
            "author": author,
            "setting": setting,
            "connection_note": connection,
            "text": _strip_excerpt_text(text_region),
        })
    return excerpts


def parse_trail(path: str | Path) -> TrailDoc:
    """Parse a trail markdown file into a TrailDoc. Raises ValueError if it has no title."""
    p = Path(path)
    text = p.read_text(encoding="utf-8")
    title = _first(_TITLE_RE, text)
    if not title:
        raise ValueError(f"{p.name}: no '# Title' line — not a trail file?")
    return TrailDoc(
        path=str(p),
        title=title,
        description=_first(_DESC_RE, text),
        rationale=_first(_RATIONALE_RE, text),
        books=_parse_books(text),
        excerpts=_parse_excerpts(text),
    )
