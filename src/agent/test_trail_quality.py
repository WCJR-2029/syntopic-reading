def test_reflow_rejoins_and_tightens_quotes():
    pytest.importorskip("dashboard")
    from dashboard.lib import reflow
    # epub artifact: isolated words + space-after-open-quote + space-before-period
    raw = "to be an entertainer, you\n\nmust\n\n. You gotta, as he said: “\n\nnervous as hell.”"
    out = reflow(raw)
    assert "you must. You gotta" in out      # isolated word rejoined + space-before-period fixed
    assert "“nervous as hell.”" in out       # space-after-open-quote tightened
    assert "“ " not in out and " ." not in out


