# ---------- T2 parser ----------
def test_parser_roundtrip(tmp_path):
    p = tmp_path / "trail.md"
    p.write_text(SAMPLE_TRAIL, encoding="utf-8")
    doc = parse_trail(p)
    assert doc.title == "Test Trail Title"
    assert doc.description.startswith("A test description")
    assert len(doc.books) == 2
    assert doc.books[0]["title"] == "Book One   Alice Author"
    assert doc.books[0]["excerpt_count"] == 2
    assert len(doc.excerpts) == 3
    assert doc.excerpts[0]["sequence_order"] == 1
    assert doc.excerpts[0]["book_title"] == "Book One   Alice Author"
    assert "First excerpt text" in doc.excerpts[0]["text"]
    assert not doc.excerpts[0]["text"].startswith(">")


