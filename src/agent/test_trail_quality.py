# ---------- T5 store ----------
def _score(fn, comp):
    scores = {k: 3 for k in rubric.DIMENSION_KEYS}
    return TrailScore(trail_file=fn, title=fn, scores=scores, composite=comp,
                      bucket=rubric.bucket_for(comp), headline={}, rationale="r", gap_note="g",
                      flags=[], facts={"book_count": 5}, hard_capped=False, model="m", ts="t")


def test_store_roundtrip(tmp_path):
    sp = tmp_path / "scores.json"
    store = {}
    store_mod.put(store, _score("a.md", 25), "hash1")
    store_mod.save_store(store, sp)
    loaded = store_mod.load_store(sp)
    assert loaded["a.md"]["composite"] == 25
    assert loaded["a.md"]["content_hash"] == "hash1"
    assert not store_mod.needs_scoring(loaded, "a.md", "hash1")
    assert store_mod.needs_scoring(loaded, "a.md", "hash2")  # changed content
    assert store_mod.needs_scoring(loaded, "a.md", "hash1", force=True)


# ---------- T6 dashboard ----------
def test_dashboard_sorted_and_summarized():
    store = {
        "low.md": _score("low.md", 16).to_dict() | {"facts": {"book_count": 3}},
        "high.md": _score("high.md", 31).to_dict() | {"facts": {"book_count": 9}},
    }
    md = render_dashboard(store)
    assert "Syntopic Library" in md
    assert "2 trails scored" in md
    # higher composite must appear before lower in the table
    assert md.index("31") < md.index("16")


