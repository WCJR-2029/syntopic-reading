def test_author_consolidation_regression():
    """The Missing Curriculum bug: a malformed lowercase Goleman title must group with the
    well-formed ones so author dominance reads 80%, not 40%."""
    items = [
        ("emotional intelligence goleman", 4),          # malformed, no delimiter
        ("Focus   Daniel Goleman", 2),
        ("Brain and Emotional Intelligence, The   Daniel Goleman", 2),
        ("Escape from Freedom   Erich Fromm", 1),
        ("The 33 Strategies of War   Robert Greene", 1),
    ]
    counts = author_counts(items)
    total = sum(counts.values())
    assert total == 10
    # all three Goleman titles collapse to one author at 8/10
    goleman = max(counts, key=counts.get)
    assert "Goleman" in goleman
    assert counts[goleman] == 8
    assert max(counts.values()) / total == 0.8


def _doc(excerpts, description="A plain description.", books=None):
    return TrailDoc(path="x", title="T", description=description, rationale="",
                    books=books or [], excerpts=excerpts)


def test_facts_author_dominance_flag():
    ex = [{"sequence_order": i, "book_title": "Solo Book   One Author",
           "author": "None", "connection_note": "", "text": f"text {i} unique words here padding"}
          for i in range(1, 6)]  # 5/5 one book+author
    facts = compute_facts(_doc(ex))
    assert facts["top_author_share"] == 1.0
    assert any("author_dominance" in f for f in facts["flags"])
    assert any("book_dominance" in f for f in facts["flags"])


def test_facts_verbatim_repeat_is_hard_flag():
    same = "this exact excerpt text repeats verbatim across two slots in the trail"
    ex = [
        {"sequence_order": 1, "book_title": "A   X", "author": "None", "connection_note": "", "text": same},
        {"sequence_order": 2, "book_title": "B   Y", "author": "None", "connection_note": "", "text": same},
        {"sequence_order": 3, "book_title": "C   Z", "author": "None", "connection_note": "", "text": "different text entirely"},
        {"sequence_order": 4, "book_title": "D   W", "author": "None", "connection_note": "", "text": "yet another distinct passage"},
    ]
    facts = compute_facts(_doc(ex))
    assert has_hard_flag(facts)
    assert any(f.startswith("HARD verbatim") for f in facts["flags"])


